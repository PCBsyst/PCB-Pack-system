import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const source = fs.readFileSync(new URL("../lib/unsaved-change-policy.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { shouldConfirmLink: confirm } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
const base = { dirty: true, currentHref: "https://example.com/candidates/test", href: "/jobs" };
assert.equal(confirm(base), true);
assert.equal(confirm({ ...base, dirty: false }), false);
assert.equal(confirm({ ...base, href: "#details" }), false);
assert.equal(confirm({ ...base, href: "/candidates/test" }), false);
assert.equal(confirm({ ...base, href: "/candidates/test?mode=other" }), true);
assert.equal(confirm({ ...base, href: "https://other.example.com" }), true);
assert.equal(confirm({ ...base, href: "mailto:sample@example.com" }), false);
assert.equal(confirm({ ...base, href: "javascript:void(0)" }), false);
assert.equal(confirm({ ...base, modified: true }), false);
assert.equal(confirm({ ...base, target: "_blank" }), false);
assert.equal(confirm({ ...base, download: true }), false);
assert.equal(confirm({ ...base, target: "_self" }), true);
console.log("Unsaved navigation policy: 12 assertions passed; actual browser dialogs remain separately tested.");
