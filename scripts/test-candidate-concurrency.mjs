import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const source = fs.readFileSync(new URL("../lib/candidate-form.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { candidateFormFromRow: fromRow, changedCandidateFields: changed } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
const input = fromRow({ name: "가상 후보자", email: "sample@example.com", birth_date: "2000-01-01" });
assert.equal(input.name, "가상 후보자");
assert.equal(input.birthDate, "2000-01-01");
assert.equal(input.phone, "");
assert.equal(fromRow({ name: null }).name, "");
assert.deepEqual(changed(input, input), []);
assert.deepEqual(changed(input, { ...input, email: "other@example.com" }), ["email"]);
assert.deepEqual(changed(input, { ...input, phone: "000", address: "가상 주소" }), ["phone", "address"]);
assert.equal(input.email, "sample@example.com");
const sql = fs.readFileSync(new URL("../supabase/migrations/202610030024_candidate_optimistic_concurrency.sql", import.meta.url), "utf8");
assert.match(sql, /for update/);
assert.match(sql, /updated_candidate\.row_version <> expected_version/);
assert.match(sql, /errcode = '40001'/);
assert.match(sql, /new\.row_version := old\.row_version \+ 1/);
assert.match(sql, /revoke execute on function public\.update_candidate_with_reason\(uuid,text,text,date,text,text,text,text,text\) from public, anon, authenticated/);
assert.ok(sql.trim().startsWith("begin;") && sql.trim().endsWith("commit;"));
console.log("Candidate conflict: 8 form checks + 6 static SQL contracts passed; real concurrent DB requests not tested.");
