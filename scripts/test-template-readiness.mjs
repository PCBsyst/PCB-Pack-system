import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const compile = (file) => ts.transpileModule(fs.readFileSync(new URL(file, import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const registry = `data:text/javascript;base64,${Buffer.from(compile("../lib/document-template-registry.ts")).toString("base64")}`;
const code = compile("../lib/template-readiness.ts").replace("@/lib/document-template-registry", registry);
const { templateReadiness: rows, readinessCount: count, isTemplateReadinessRows: valid, confirmPackageReadiness: preflight } = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const builtin = rows(new Set());
assert.equal(valid(builtin), true);
assert.equal(valid([null, null, null, null, null, null]), false);
assert.equal(valid([...builtin.slice(1), builtin[1]]), false);
assert.equal(valid(builtin.map((row) => ({ ...row, source: "UNKNOWN" }))), false);
assert.equal(builtin.length, 6);
assert.equal(count(builtin, { KR: true, EN: true }, 2).available, 6);
assert.equal(count(builtin, { KR: true, EN: true }, 2).expected, 12);
assert.equal(count(builtin, { KR: true, EN: false }, 1).missing.length, 1);
assert.equal(count(builtin, { KR: false, EN: false }, 1).expected, 0);
const all = rows(new Set(["APPLICATION_REVIEW:EN", "CERTIFICATION_DECISION_REPORT:EN", "DELIVERY_CONFIRMATION:KR", "APPLICATION_REVIEW:KR"]));
assert.equal(all.find((row) => row.id === "application-review-kr").source, "DATABASE");
assert.equal(count(all, { KR: true, EN: true }, 3).available, 18);
assert.equal(count(all, { KR: true, EN: true }, 3).missing.length, 0);
let confirmations = 0;
assert.equal(preflight(all, { KR: true, EN: true }, 1, () => { confirmations++; return false; }), "GENERATE");
assert.equal(confirmations, 0);
assert.equal(preflight(builtin, { KR: true, EN: true }, 1, (message) => { assert.match(message, /누락 양식/); assert.match(message, /전체 완료로 처리되지/); return false; }), "CANCEL");
assert.equal(preflight(builtin, { KR: true, EN: false }, 2, () => true), "GENERATE");
assert.equal(preflight(builtin, { KR: true, EN: true }, 0, () => { throw new Error("빈 패키지는 확인하지 않아야 합니다."); }), "EMPTY");
assert.equal(preflight(builtin.map((row) => ({ ...row, source: "MISSING" })), { KR: true, EN: true }, 1, () => false), "EMPTY");
console.log("국문·영문 양식 준비 및 선택 범위 집계 검사: 통과");
