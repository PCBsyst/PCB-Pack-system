import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const code = ts.transpileModule(fs.readFileSync(new URL("../lib/job-certificate-reconciliation.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { reconcileJobCertificate: check } = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const row = { id: "cert-a", job_id: "a", certification_no: "26750032", issue_date: "2026-10-02", valid_until: "2029-10-01" };
const input = { certificationNo: row.certification_no, issueDate: row.issue_date, expiryDate: row.valid_until };
assert.equal(check("a", input, [row], true).status, "MATCH");
assert.equal(check("a", { ...input, certificationNo: "different" }, [row], true).status, "MISMATCH");
assert.deepEqual(check("a", { ...input, issueDate: "wrong", expiryDate: "wrong" }, [row], true).differences, ["발행일", "만료일"]);
assert.equal(check("a", undefined, [row], true).status, "REGISTRY_ONLY");
assert.equal(check("a", input, [], true).status, "WORKFLOW_ONLY");
assert.equal(check("a", undefined, [], true).status, "EMPTY");
assert.equal(check("a", input, [row], false).status, "UNVERIFIED");
assert.equal(check("a", input, [row], false).certificate, undefined);
assert.equal(check("a", input, [row, { ...row, id: "cert-b" }], true).status, "AMBIGUOUS");
assert.equal(check("a", input, [row, { ...row, id: "cert-b" }], true).certificate, undefined);
assert.equal(check("other", undefined, [row], true).status, "EMPTY");
assert.equal(check("a", { ...input, certificationNo: ` ${row.certification_no} ` }, [row], true).status, "MATCH");
assert.equal(check("a", { certificationNo: 42 }, [row], true).status, "REGISTRY_ONLY");
assert.equal(input.certificationNo, row.certification_no);
const ui = fs.readFileSync(new URL("../components/jobs-table.tsx", import.meta.url), "utf8");
assert.match(ui, /\.eq\("history_state", "CURRENT"\)/);
assert.match(ui, /if \(cancelled\) return;/);
assert.match(ui, /const certificate = comparison.certificate/);
assert.match(ui, /전체 원장 대조/);
assert.doesNotMatch(ui, /\.update\(|\.upsert\(/);
console.log("Job 원장·업무 입력 대조 및 조회 실패·복수 현재 기록 검사: 통과 (실제 DB/화면 검증은 별도)");
