import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../lib/certification-expiry.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { koreaToday, expiryDays, expiryBucket } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
assert.equal(koreaToday(new Date('2026-10-02T15:00:00Z')), '2026-10-03');
assert.equal(expiryDays('2026-10-03', '2026-10-03'), 0);
assert.equal(expiryDays('2026-11-02', '2026-10-03'), 30);
assert.equal(expiryDays('2026-10-02', '2026-10-03'), -1);
assert.equal(expiryDays('2028-03-01', '2028-02-28'), 2);
assert.equal(expiryDays('2026-02-30', '2026-02-28'), null);
assert.equal(expiryDays('', '2026-10-03'), null);
assert.equal(expiryDays('2026-10-03', 'not a date'), null);
assert.equal(expiryBucket(null), 'unknown');
assert.equal(expiryBucket(-1), 'past');
assert.equal(expiryBucket(0), 'today');
assert.equal(expiryBucket(30), 'upcoming');
console.log('Certification expiry: 12 cases passed');
