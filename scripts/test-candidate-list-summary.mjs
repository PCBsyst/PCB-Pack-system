import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const code = ts.transpileModule(fs.readFileSync(new URL("../lib/candidate-list-summary.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { candidateRecordSummary: summary } = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const first = { id: "app-one", jobId: "job-one", jobNo: "QMS260001", certificationState: "ACTIVE" };
const second = { id: "app-one", jobId: "job-two", jobNo: "EMS260001", certificationState: "NONE" };
assert.equal(summary([first, second, first]).jobs, 2);
assert.equal(summary([first, second]).applications, 1);
assert.equal(summary([first, { ...second, id: "app-two" }]).applications, 2);
assert.equal(summary([first, second]).certification, "ACTIVE");
for (const state of ["NONE", "SUSPENDED", "WITHDRAWN"]) assert.equal(summary([{ ...first, certificationState: state }]).certification, "NO_ACTIVE");
assert.equal(summary([{ ...first, certificationState: undefined }]).certification, "UNKNOWN");
assert.equal(summary([{ ...first, certificationState: "INVALID" }]).certification, "UNKNOWN");
assert.equal(summary([{ ...first, certificationState: undefined }, second]).certification, "UNKNOWN");
assert.equal(summary([]).jobs, 0);
assert.equal(summary([]).applications, 0);
assert.equal(summary([]).certification, "NO_ACTIVE");
assert.equal(summary([{ ...first, jobId: undefined }, { ...first, jobId: undefined, id: "different-app" }]).jobs, 2);
const ui = fs.readFileSync(new URL("../components/candidates-table.tsx", import.meta.url), "utf8");
assert.match(ui, /useLinkedRecordsState\(revision\)/);
assert.match(ui, /if \(cancelled\) return;/);
assert.match(ui, /신청 수 \/ Job 수/);
assert.doesNotMatch(ui, /readPrototypeWorkflow/);
assert.match(ui, /!archiveNotice && storage/);
assert.match(ui, /인증상태 미확인/);
const hook = fs.readFileSync(new URL("../components/prototype-linked-rows.tsx", import.meta.url), "utf8");
assert.match(hook, /certificationState: job.certification_state/);
console.log("후보자 신청·Job 중복 집계 및 저장 인증상태 검사: 통과 (실제 화면·권한 확인은 별도)");
