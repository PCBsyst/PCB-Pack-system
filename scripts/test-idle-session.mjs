import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const source = fs.readFileSync(new URL("../lib/idle-session.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { idleState, idleStorageKey, IDLE_LIMIT_MS } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
const last = 10000000;
assert.equal(idleState(last, last), "active");
assert.equal(idleState(last, last + 55 * 60000 - 1), "active");
assert.equal(idleState(last, last + 55 * 60000), "warning");
assert.equal(idleState(last, last + IDLE_LIMIT_MS - 1), "warning");
assert.equal(idleState(last, last + IDLE_LIMIT_MS), "expired");
assert.equal(idleState(last, last + 8 * IDLE_LIMIT_MS), "expired");
assert.equal(idleState(NaN, last), "expired");
assert.equal(idleState(0, last), "expired");
assert.equal(idleState(last + 1, last), "expired");
const token = `header.${Buffer.from(JSON.stringify({ session_id: "test-session" })).toString("base64url")}.signature`;
assert.equal(idleStorageKey("user-1", token), "certification-idle:user-1:test-session");
assert.notEqual(idleStorageKey("user-1", token), idleStorageKey("user-2", token));
assert.equal(idleStorageKey("user-1", "invalid"), "certification-idle:user-1:session");
console.log("Idle session policy: 12 assertions passed. Browser/real logout tests remain separate.");
