result=compare([{standard:'ISO 9001'},{standard:'ISO 45001'}],original);assert.equal(result.countMismatch,false);assert.deepEqual(Array.from(result.missingStandards),['ISO 50001']);assert.deepEqual(Array.from(result.unexpectedStandards),['ISO 45001']);assert.equal(result.matched,false);
result=compare([{standard:'iso 9001'},{standard:' ISO 50001 '}],original);assert.equal(result.matched,true);
result=compare([{standard:'ISO 9001'}],parse('2',''));assert.equal(result.countMismatch,true);assert.equal(result.standardsProvided,false);
