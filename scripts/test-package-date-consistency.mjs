import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const code = ts.transpileModule(fs.readFileSync(new URL("../lib/package-date-consistency.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { packageDateDifferences: differences } = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const record = date => ({ applicability: "REQUIRED", received: true, date, comment: "" });
const input = { examSchedules: { j1: { examNoticeDate: "2026-09-01", examDate: "2026-09-08" } }, certificates: { j1: { issueDate: "2026-09-15" } }, deliveryDocuments: { j1: { examNotice: record("2026-09-01"), examAnswers: record("2026-09-08"), certificate: record("2026-09-15") } } };
assert.deepEqual(differences([{ id: "j1" }], input), []);
const changed = structuredClone(input);
for (const row of Object.values(changed.deliveryDocuments.j1)) row.date = "2026-09-16";
const original = JSON.stringify(changed);
const found = differences([{ id: "j1" }], changed);
assert.equal(found.length, 3);
assert.deepEqual(found.map(row => row.key), ["examNotice", "examAnswers", "certificate"]);
assert.equal(found[0].sourceDate, "2026-09-01");
assert.equal(found[0].documentDate, "2026-09-16");
assert.equal(JSON.stringify(changed), original);
assert.deepEqual(differences([{ id: "other" }], changed), []);
assert.deepEqual(differences([], changed), []);
assert.deepEqual(differences([{ id: "j1" }], { certificates: {}, deliveryDocuments: {} }), []);
const excluded = structuredClone(changed);
excluded.deliveryDocuments.j1.examNotice.applicability = "NOT_APPLICABLE";
excluded.deliveryDocuments.j1.examAnswers.received = false;
excluded.deliveryDocuments.j1.certificate.date = "";
assert.deepEqual(differences([{ id: "j1" }], excluded), []);
const noSource = structuredClone(changed);
noSource.examSchedules.j1.examNoticeDate = "";
noSource.examSchedules.j1.examDate = "";
noSource.certificates.j1.issueDate = "";
assert.deepEqual(differences([{ id: "j1" }], noSource), []);
const ui = fs.readFileSync(new URL("../components/application-detail.tsx", import.meta.url), "utf8");
assert.ok(ui.includes("<PackageDateConsistency jobs={linkedJobs} context={packageContext}"));
assert.ok(ui.includes('id={`delivery-${job.id}-${row.key}`}'));
assert.ok(ui.includes('href={`#delivery-${item.jobId}-${item.key}`}'));
console.log("패키지 날짜 대조: 차이·동일·미입력·해당없음·대상 범위·원본 유지 검사 통과");
