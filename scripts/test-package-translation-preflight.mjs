import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import vm from "node:vm";

const source = readFileSync("components/application-detail.tsx", "utf8");
const ast = ts.createSourceFile("ui.tsx", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const fn = ast.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === "PackageTranslationPreflight");
assert.ok(fn);
const code = ts.transpileModule(fn.getText(ast), { compilerOptions: { jsx: ts.JsxEmit.React, target: ts.ScriptTarget.ES2020 } }).outputText;
const helper = ts.transpileModule(readFileSync("lib/document-translation-checks.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const helperContext = vm.createContext({ exports: {} });
vm.runInContext(helper, helperContext);
const runtime = vm.createContext({ React: { createElement: (tag, props, ...children) => ({ tag, props, children }) }, documentTranslationIssues: helperContext.exports.documentTranslationIssues });
vm.runInContext(code + "\nthis.render = PackageTranslationPreflight;", runtime);
const text = tree => typeof tree === "string" ? tree : Array.isArray(tree) ? tree.map(text).join(" ") : tree?.children ? tree.children.map(text).join(" ") : "";
const jobs = [{ id: "a", jobNo: "QMS260001", standard: "ISO 9001" }, { id: "b", jobNo: "EMS260001", standard: "ISO 14001" }];
const context = { jobs, review: { comment: "검토 완료", verificationComment: "" }, panelMembers: [{ name: "김위원", selected: true, comment: "승인" }, { name: "박위원", selected: false, comment: "선택 안 함" }], decisions: { a: { comment: "승인" }, b: { comment: "" } }, englishText: {} };
const render = (languages, current = context, currentJobs = jobs) => runtime.render({ jobs: currentJobs, context: current, languages });
const kr = text(render({ KR: true, EN: false }));
assert.match(kr, /선택 언어:.*국문/);
assert.match(kr, /번역 입력 점검은 적용하지 않습니다/);
assert.doesNotMatch(kr, /입력 필요/);
assert.match(text(render({ KR: false, EN: false })), /하나 이상 선택/);
const pending = text(render({ KR: true, EN: true }));
assert.match(pending, /서류검토 의견 \(영문\)/);
assert.match(pending, /김위원 위원 의견 \(영문\)/);
assert.match(pending, /QMS260001 최종 승인 의견 \(영문\)/);
assert.doesNotMatch(pending, /EMS260001 최종 승인 의견/);
assert.doesNotMatch(pending, /박위원 위원 의견/);
const complete = { ...context, englishText: { reviewComment: "Reviewed", panelComments: { 김위원: "Approved" }, decisionComments: { a: "Approved" } } };
assert.doesNotMatch(text(render({ KR: false, EN: true }, complete)), /입력 필요/);
assert.match(text(render({ KR: false, EN: true }, complete)), /담당자가 검토/);
assert.match(text(render({ KR: true, EN: true }, context, [])), /연결된 Job이 없어/);
const links = [];
function walk(tree) { if (!tree || typeof tree !== "object") return; if (Array.isArray(tree)) return tree.forEach(walk); if (tree.props?.href) links.push(tree.props.href); tree.children?.forEach(walk); }
walk(render({ KR: true, EN: true }));
assert.ok(links.length > 0 && links.every(href => href === "#english-document-input"));
assert.ok(source.includes('id="english-document-input"'));
assert.ok(source.indexOf("<PackageTranslationPreflight jobs=") < source.indexOf('label={`${job.jobNo} · 국문 초안 DOCX`}'));
console.log("영문 생성 전 점검: 국문 기본·언어 미선택·양식/Job/선택위원별 번역 누락·보완 이동·입력 완료/정확성 구분 검사 통과 (브라우저 별도)");
