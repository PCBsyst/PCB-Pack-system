import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const code = ts.transpileModule(fs.readFileSync(new URL("../lib/workspace-save-queue.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { createWorkspaceSaveQueue } = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const queue = createWorkspaceSaveQueue();
const calls = [];
let release;
const first = queue.enqueue(async () => { calls.push("old-start"); await new Promise(done => release = done); calls.push("old-end"); });
const second = queue.enqueue(async () => { calls.push("new"); });
await new Promise(resolve => setImmediate(resolve));
assert.deepEqual(calls, ["old-start"]);
release();
assert.equal(await first, true); assert.equal(await second, true);
assert.deepEqual(calls, ["old-start", "old-end", "new"]);
const failure = queue.enqueue(async () => { throw new Error("db failure"); });
const retry = queue.enqueue(async () => { calls.push("retry"); });
await assert.rejects(failure, /db failure/);
assert.equal(await retry, true);
let allowed = false;
const skipped = queue.enqueue(async () => { assert.fail("취소된 저장 실행 금지"); }, () => allowed);
assert.equal(await skipped, false);
allowed = true;
assert.equal(await queue.enqueue(async () => { calls.push("after-cancel"); }, () => allowed), true);
let finishBlocker;
const blocker = queue.enqueue(async () => { await new Promise(done => finishBlocker = done); });
let stillAllowed = true;
const revoked = queue.enqueue(async () => { assert.fail("대기 중 권한 변경 후 저장 금지"); }, () => stillAllowed);
await new Promise(resolve => setImmediate(resolve));
stillAllowed = false;
finishBlocker(); await blocker;
assert.equal(await revoked, false);
const source = fs.readFileSync(new URL("../components/application-detail.tsx", import.meta.url), "utf8");
assert.equal(source.split("saveQueue.current!.enqueue").length - 1, 2);
assert.ok(source.includes("active && saveAccess.current.key === storageKey && saveAccess.current.canEdit"));
assert.ok(source.includes("state: JSON.parse(snapshot)"));
console.log("업무 저장 순서: 이전 요청 완료 후 최신 요청·실패 후 재시도·취소 시 미실행·자동/수동 동일 큐 검사 통과 (다른 탭/운영 DB 동시성 검증 별도)");
