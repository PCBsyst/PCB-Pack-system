import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const code = ts.transpileModule(fs.readFileSync(new URL("../lib/document-delivery-values.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { documentDeliveryValues: values } = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const context = { application: { receivedAt: "2026-09-01", primaryOwner: "가상 담당자" }, review: { reviewedAt: "2026-09-02", verifiedAt: "2026-09-03" }, decisionDate: "2026-09-04", finalApprovalDate: "2026-09-07", invoiceNo: "TEST-001", invoiceIssuedAt: "2026-09-03", paymentConfirmedAt: "2026-09-04", certificates: { j1: { draftIssuedAt: "2026-09-08", issueDate: "2026-09-09", expiryDate: "2029-09-08", originalSentAt: "", trackingNumber: "" } } };
const original = JSON.stringify(context);
const kr = values(context, "j1", "KR");
const en = values(context, "j1", "EN");
assert.match(kr.chronology, /서류 검토일: 2026-09-02/);
assert.match(en.chronology, /Certificate issued: 2026-09-09/);
assert.match(kr.chronology, /인증 만료일: 2029-09-08/);
assert.match(en.chronology, /Certificate expiry: 2029-09-08/);
assert.match(kr.invoiceNote, /입금일: 2026-09-04/);
assert.match(en.invoiceNote, /Paid: 2026-09-04/);
assert.equal(kr.dispatchNote, "");
assert.equal(kr.originalSentAt, "-");
assert.equal(JSON.stringify(context), original);
const noInvoiceNumber = structuredClone(context); noInvoiceNumber.invoiceNo = "";
assert.match(values(noInvoiceNumber, "j1", "KR").invoiceNote, /인보이스: - \/ 발행일: 2026-09-03 \/ 입금일: 2026-09-04/);
const onlyPaid = structuredClone(noInvoiceNumber); onlyPaid.invoiceIssuedAt = "";
assert.match(values(onlyPaid, "j1", "KR").invoiceNote, /발행일: - \/ 입금일: 2026-09-04/);
const noInvoice = structuredClone(onlyPaid); noInvoice.paymentConfirmedAt = "";
assert.equal(values(noInvoice, "j1", "KR").invoiceNote, "");
const noExpiry = structuredClone(context); noExpiry.certificates.j1.expiryDate = "";
assert.match(values(noExpiry, "j1", "KR").chronology, /인증 만료일: -/);
const trackingOnly = structuredClone(context); trackingOnly.certificates.j1.trackingNumber = "TEST-TRACK";
assert.match(values(trackingOnly, "j1", "KR").dispatchNote, /원본 송부일: - \/ 운송장 번호: TEST-TRACK/);
assert.equal(values(context, "missing", "EN").issueDate, "-");
assert.equal(values(context, "missing", "EN").dispatchNote, "");
for (const key of ["receivedAt", "reviewedAt", "verifiedAt", "decisionDate", "finalApprovalDate", "draftIssuedAt", "issueDate", "expiryDate", "invoiceIssuedAt", "paymentConfirmedAt"]) assert.match(kr[key], /^\d{4}-\d{2}-\d{2}$/);
const route = fs.readFileSync(new URL("../app/api/documents/delivery-confirmation/route.ts", import.meta.url), "utf8");
assert.ok(route.includes("...delivery,"));
assert.ok(route.includes("delivery.chronology"));
console.log("문서전달확인서: 국영문 기록 날짜·운송장·미입력 비추정·원본 유지 검사 통과");
