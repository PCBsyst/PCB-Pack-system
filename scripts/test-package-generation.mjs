import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const source = fs.readFileSync(new URL("../lib/package-generation.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { parsePackageGeneration: parse } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
const headers = (count, complete, date = "2026-10-03T01:00:00Z") => new Headers({ "X-Package-File-Count": String(count), "X-Package-Complete": String(complete), "X-Package-Generated-At": date });
assert.equal(parse(headers(3, true), ["job-1"], ["KR"]).complete, true);
assert.equal(parse(headers(3, false), ["job-1"], ["KR", "EN"]).complete, false);
assert.equal(parse(headers(6, true), ["job-1"], ["KR", "EN"]).format, "DOCX_ZIP");
assert.throws(() => parse(headers(0, false), ["job-1"], ["KR"]));
assert.throws(() => parse(headers(2, true), ["job-1"], ["KR"]));
assert.throws(() => parse(headers(1.5, false), ["job-1"], ["KR"]));
assert.throws(() => parse(headers(3, "invalid"), ["job-1"], ["KR"]));
assert.throws(() => parse(headers(3, true, "invalid"), ["job-1"], ["KR"]));
assert.throws(() => parse(new Headers(), ["job-1"], ["KR"]));
const recorded = headers(3, true);
recorded.set("X-Package-Receipt-Status", "RECORDED");
assert.throws(() => parse(recorded, ["job-1"], ["KR"]));
recorded.set("X-Package-Receipt-Id", "test-receipt");
recorded.set("X-Package-SHA256", "a".repeat(64));
assert.equal(parse(recorded, ["job-1"], ["KR"]).receiptStatus, "RECORDED");
recorded.set("X-Package-SHA256", "invalid");
assert.throws(() => parse(recorded, ["job-1"], ["KR"]));
console.log("Package generation receipts: 12 assertions passed; real file/download tests remain separate.");
