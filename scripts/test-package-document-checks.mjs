import assert from "node:assert/strict";
import fs from "node:fs";
import ts from "typescript";
const code = ts.transpileModule(fs.readFileSync(new URL("../lib/package-document-checks.ts", import.meta.url), "utf8"), { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { packageDocumentIssues: check } = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const jobs = [{ id: "one" }, { id: "two" }];
const rows = [{ key: "education", document: "교육 수료증" }];
const record = (applicability, received, date) => ({ education: { applicability, received, date } });
assert.equal(check(jobs, {}, rows).length, 2);
assert.match(check([jobs[0]], { one: record("REQUIRED", false, "") }, rows)[0].reason, /확인 여부·날짜/);
assert.equal(check([jobs[0]], { one: record("REQUIRED", true, " ") }, rows).length, 1);
assert.equal(check([jobs[0]], { one: record("REQUIRED", true, "2026-10-02") }, rows).length, 0);
assert.equal(check([jobs[0]], { one: record("CONDITIONAL", false, "") }, rows).length, 0);
assert.equal(check([jobs[0]], { one: record("CONDITIONAL", true, "") }, rows).length, 1);
assert.equal(check([jobs[0]], { one: record("NOT_APPLICABLE", false, "") }, rows).length, 0);
assert.equal(check([jobs[0]], { one: record("UNKNOWN", true, "2026-10-02") }, rows).length, 1);
assert.equal(check(jobs, { one: record("REQUIRED", true, "2026-10-02") }, rows)[0].jobId, "two");
const ui = fs.readFileSync(new URL("../components/application-detail.tsx", import.meta.url), "utf8");
assert.match(ui, /const issues = packageDocumentIssues\(linkedJobs/);
assert.match(ui, /const issues = packageDocumentIssues\(jobs/);
assert.match(ui, /href=\{`#delivery-/);
console.log("패키지 문서 누락·적용 기준 및 화면/생성 공통 점검: 통과");
